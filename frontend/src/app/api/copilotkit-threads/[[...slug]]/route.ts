import {
  CopilotRuntime,
  CopilotKitIntelligence,
  InMemoryAgentRunner,
  createCopilotRuntimeHandler,
} from "@copilotkit/runtime/v2";
import { HttpAgent } from "@ag-ui/client";

/**
 * The Intelligence-enabled runtime. All three Rich Threads routes — the
 * prebuilt drawer, the headless thread list, and the lifecycle page — run on
 * this one endpoint.
 *
 * `/api/copilotkit` is the plain Quickstart runtime and has no thread routes.
 * This one adds the `intelligence` option the Quickstart and Headless Threads
 * pages both describe: a `CopilotKitIntelligence` instance holding the project
 * key, which is what persists and replays thread history.
 *
 * `CPK_INTELLIGENCE_API_KEY` is the variable name the .NET docs use (the
 * Python pages call it `INTELLIGENCE_API_KEY`). It is read server-side only.
 * Leave it unset and the block below is skipped entirely: the read-only thread
 * routes still answer off the in-memory runner's local-dev fallback, mutations
 * return 422, and the prebuilt drawer stays locked.
 */

const AGENT_URL = process.env.MS_AGENT_URL ?? "http://localhost:8000";

const INTELLIGENCE_API_KEY = process.env.CPK_INTELLIGENCE_API_KEY;

const mainAgent = () => new HttpAgent({ url: `${AGENT_URL}/` });

const runtime = new CopilotRuntime({
  // `default` is registered because `<CopilotThreadsDrawer>` and `useThreads`
  // fall back to DEFAULT_AGENT_ID ("default") when no agentId is given, and
  // threads are stored per agent id. `my_agent` mirrors the main runtime so the
  // same prompts work on both.
  agents: {
    default: mainAgent(),
    my_agent: mainAgent(),
    chart_agent: new HttpAgent({ url: `${AGENT_URL}/chart_agent` }),
    search_agent: new HttpAgent({ url: `${AGENT_URL}/search_agent` }),
  },

  ...(INTELLIGENCE_API_KEY
    ? {
        // [1] quickstart / headless-threads: intelligence
        // [!code highlight]
        intelligence: new CopilotKitIntelligence({
          apiKey: INTELLIGENCE_API_KEY,
          ...(process.env.INTELLIGENCE_API_URL
            ? { apiUrl: process.env.INTELLIGENCE_API_URL }
            : {}),
          ...(process.env.INTELLIGENCE_GATEWAY_WS_URL
            ? { wsUrl: process.env.INTELLIGENCE_GATEWAY_WS_URL }
            : {}),
        }),

        // Thread names are auto-generated by the LLM after the first message.
        // Spelled out rather than left to the default so the flag is visible
        // next to the docs' `generateThreadNames: false`.
        // [2] headless-threads: runtime options
        // [!code highlight]
        generateThreadNames: true,

        // Threads are per-user. The Quickstart's own words: without this,
        // every visitor shares one history. A fixed id keeps one shared list
        // across browsers for manual QA — send `x-user-id` to check that two
        // users get two separate lists.
        // [3] quickstart / threads-lifecycle: scope threads to the user
        // [!code highlight]
        identifyUser: (request: Request) => ({
          id: request.headers.get("x-user-id") ?? "anonymous",
          name: request.headers.get("x-user-name") ?? "Anonymous",
        }),
      }
    : { runner: new InMemoryAgentRunner() }),
});

const handler = createCopilotRuntimeHandler({
  runtime,
  basePath: "/api/copilotkit-threads",
});

export const GET = handler;
export const POST = handler;
export const PATCH = handler;
export const DELETE = handler;
